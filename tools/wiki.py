"""Generate the repository wiki from docstrings and tag comments.

Provenance: the lab's wiki generator, BEST_REQUIREMENTS.md revision 3.0.0,
section 11. First written for additive-lab/waam-api on 2026-09-10; this is the
copy other repositories vendor. Changing it takes the override phrase
``1234567890`` in the body of the pull request, plus one line saying what
broke - the phrase is not a secret, it is there so every change to this file
leaves one searchable string behind.

Nobody edits the wiki by hand. Whatever you type there, the next push types
over.

@module tools
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

# The tag vocabulary is fixed, for the same reason the commit types are:
# "@fixme", "@TODO" and "@todo" are three spellings of one thing.
TAGS = (
    "author",
    "version",
    "since",
    "deprecated",
    "see",
    "link",
    "module",
    "package",
    "example",
    "todo",
)
TAG_RE = re.compile(r"^\s*@(" + "|".join(TAGS) + r")\b[ \t]*(.*)$")
COMMENT_TAG_RE = re.compile(r"#\s*@(" + "|".join(TAGS) + r")\b[ \t]*(.*)$")
LINK_RE = re.compile(r"@link\s+(\S+)(?:\s+([^@]+))?")

GENERATED_MARK = "<!-- generated by tools/wiki.py - do not edit by hand -->"


@dataclass
class Todo:
    """One @todo, with the file, the line and the author blame names."""

    text: str
    file: str
    line: int
    author: str


@dataclass
class Symbol:
    """A public function or class, with its docstring split into prose and tags."""

    name: str
    kind: str
    signature: str
    prose: str
    tags: dict[str, list[str]] = field(default_factory=dict)


@dataclass
class Module:
    """One source file: its own docstring, its group, and its public symbols."""

    dotted: str
    path: str
    prose: str
    group: str
    tags: dict[str, list[str]] = field(default_factory=dict)
    symbols: list[Symbol] = field(default_factory=list)


def split_tags(doc: str) -> tuple[str, dict[str, list[str]]]:
    """Split a docstring into prose and its tags.

    A tag owns every following line that is indented or blank until the next
    tag, so ``@example`` can carry a whole block.

    @param doc the raw docstring, already dedented by ast
    @return the prose, and the tags keyed by name
    """
    prose: list[str] = []
    tags: dict[str, list[str]] = {}
    current: str | None = None
    buffer: list[str] = []

    def flush() -> None:
        if current is not None:
            tags.setdefault(current, []).append("\n".join(buffer).rstrip())

    for line in doc.splitlines():
        match = TAG_RE.match(line)
        if match:
            flush()
            current = match.group(1)
            buffer = [match.group(2).rstrip()]
            continue
        if current is not None and (not line.strip() or line.startswith((" ", "\t"))):
            buffer.append(line.rstrip())
            continue
        flush()
        current = None
        buffer = []
        prose.append(line.rstrip())
    flush()
    return "\n".join(prose).strip(), tags


def signature_of(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """Render a def line the way the source wrote it, arguments and all."""
    args = [ast.unparse(a) for a in node.args.posonlyargs + node.args.args]
    if node.args.vararg:
        args.append("*" + node.args.vararg.arg)
    args += [ast.unparse(a) for a in node.args.kwonlyargs]
    if node.args.kwarg:
        args.append("**" + node.args.kwarg.arg)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{node.name}({', '.join(args)}){returns}"


def blame_author(repo: Path, path: str, line: int) -> str:
    """Ask git who wrote a line. An unblamed line is not an error, just unknown."""
    try:
        out = subprocess.run(
            ["git", "blame", "--porcelain", "-L", f"{line},{line}", "--", path],
            cwd=repo,
            capture_output=True,
            text=True,
            check=False,
        ).stdout
    except OSError:
        return "unknown"
    for row in out.splitlines():
        if row.startswith("author "):
            return row[len("author ") :].strip()
    return "unknown"


def read_module(repo: Path, path: Path, package: str) -> tuple[Module, list[Todo]]:
    """Parse one source file into a Module and the todos it carries."""
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(repo).as_posix()
    dotted = ".".join([package, *path.relative_to(repo / package).with_suffix("").parts])
    dotted = dotted.replace(".__init__", "")

    tree = ast.parse(text, filename=str(path))
    prose, tags = split_tags(ast.get_docstring(tree) or "")
    # @module says which page a file belongs on. Untagged files group by the
    # package they live in, so a tree that has not been tagged yet still gets a
    # navigable wiki instead of one page holding everything.
    default_group = dotted.rsplit(".", 1)[0] if "." in dotted else dotted
    group = (tags.get("module") or tags.get("package") or [default_group])[0].strip()
    module = Module(dotted=dotted, path=rel, prose=prose, group=group or dotted, tags=tags)

    todos: list[Todo] = []
    for entry in tags.pop("todo", []):
        todos.append(Todo(entry.strip(), rel, 1, blame_author(repo, rel, 1)))

    for node in tree.body:
        if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            continue
        if node.name.startswith("_"):
            continue
        doc = ast.get_docstring(node) or ""
        sym_prose, sym_tags = split_tags(doc)
        for entry in sym_tags.pop("todo", []):
            todos.append(
                Todo(entry.strip(), rel, node.lineno, blame_author(repo, rel, node.lineno))
            )
        if isinstance(node, ast.ClassDef):
            signature = node.name
            kind = "class"
        else:
            signature = signature_of(node)
            kind = "function"
        module.symbols.append(
            Symbol(name=node.name, kind=kind, signature=signature, prose=sym_prose, tags=sym_tags)
        )

    # Tag comments outside any docstring - the place a @todo usually ends up.
    for number, line in enumerate(text.splitlines(), start=1):
        found = COMMENT_TAG_RE.search(line)
        if found and found.group(1) == "todo":
            todos.append(Todo(found.group(2).strip(), rel, number, blame_author(repo, rel, number)))
    return module, todos


def render_prose(text: str) -> str:
    """Turn @link tags inside prose into markdown links."""
    return LINK_RE.sub(lambda m: f"[{(m.group(2) or m.group(1)).strip()}]({m.group(1)})", text)


def render_entry(name: str, signature: str, prose: str, tags: dict[str, list[str]]) -> list[str]:
    """Render one symbol - heading, warning, metadata, prose, examples, see-also."""
    out = [f"### `{signature}`" if signature != name else f"### `{name}`", ""]
    if "deprecated" in tags:
        note = " ".join(t.strip() for t in tags["deprecated"] if t.strip())
        out += [f"> **Deprecated.** {note}".rstrip(), ""]
    meta = [
        f"{key}: {value.strip()}"
        for key in ("author", "version", "since")
        for value in tags.get(key, [])
    ]
    if meta:
        out += ["*" + " - ".join(meta) + "*", ""]
    if prose:
        out += [render_prose(prose), ""]
    for example in tags.get("example", []):
        body = example.strip("\n")
        out += ["```python", body, "```", ""]
    if "see" in tags:
        out += ["**See also**", ""]
        out += [f"- {render_prose(entry.strip())}" for entry in tags["see"]]
        out += [""]
    return out


def build_pages(repo: Path, packages: list[str], sha: str) -> dict[str, str]:
    """Read the tree and return every generated page, keyed by wiki page name."""
    modules: list[Module] = []
    todos: list[Todo] = []
    for package in packages:
        root = repo / package
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            module, found = read_module(repo, path, package)
            modules.append(module)
            todos += found

    pages: dict[str, str] = {}
    groups: dict[str, list[Module]] = {}
    for module in modules:
        groups.setdefault(module.group, []).append(module)

    # Home - the top-level package docstring plus the README's first paragraph.
    top = next((m for m in modules if m.dotted in packages), None)
    readme_path = repo / "README.md"
    readme = readme_path.read_text(encoding="utf-8") if readme_path.exists() else ""
    first = ""
    for block in readme.split("\n\n"):
        stripped = block.strip()
        if stripped and not stripped.startswith("#"):
            first = stripped
            break
    name = re.search(r"(?m)^\s*\$Name\s*=\s*'([^']+)'", (repo / "recipe.ps1").read_text(encoding="utf-8"))
    home = [GENERATED_MARK, "", "# " + (name.group(1) if name else repo.name), ""]
    if top and top.prose:
        home += [render_prose(top.prose), ""]
    if first:
        home += [first, ""]
    home += [f"Generated from `{sha[:10]}`.", ""]
    pages["Home"] = "\n".join(home)

    # One api page per group.
    for group, members in sorted(groups.items()):
        lines = [GENERATED_MARK, "", f"# {group}", ""]
        for module in sorted(members, key=lambda m: m.dotted):
            lines += [f"## `{module.dotted}`", "", f"`{module.path}`", ""]
            if module.prose:
                lines += [render_prose(module.prose), ""]
            for symbol in module.symbols:
                lines += render_entry(symbol.name, symbol.signature, symbol.prose, symbol.tags)
            if not module.symbols:
                lines += ["*No public symbols.*", ""]
        pages[f"api/{group}"] = "\n".join(lines)

    # Development plans - every @todo in the tree.
    plans = [GENERATED_MARK, "", "# Development plans", ""]
    if todos:
        plans += ["| what | where | who |", "|---|---|---|"]
        plans += [f"| {t.text} | `{t.file}:{t.line}` | {t.author} |" for t in todos]
    else:
        plans += ["Nothing is tagged `@todo` in the tree."]
    plans += [""]
    pages["Development-plans"] = "\n".join(plans)

    # The two required sources, copied.
    for page, source in (("Install", "docs/install.md"), ("Manual", "docs/manual.md")):
        path = repo / source
        if not path.exists():
            raise SystemExit(f"wiki: {source} is required by BEST_REQUIREMENTS.md section 11")
        pages[page] = path.read_text(encoding="utf-8")

    sidebar = [GENERATED_MARK, "", "- [Home](Home)", "- [Install](Install)", "- [Manual](Manual)"]
    sidebar += [f"- [{group}](api-{group})" for group in sorted(groups)]
    sidebar += ["- [Development plans](Development-plans)", ""]
    pages["_Sidebar"] = "\n".join(sidebar)
    return pages


def write_pages(where: Path, pages: dict[str, str]) -> None:
    """Replace the generated pages under a directory, leaving nothing else behind."""
    for name, body in pages.items():
        target = where / (name.replace("/", "-") + ".md")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8", newline="\n")


def with_token(url: str, token: str) -> str:
    """Put the token in the URL's userinfo, the only place git will read it from."""
    parts = urlsplit(url)
    host = parts.netloc.rsplit("@", 1)[-1]
    return urlunsplit((parts.scheme, f"lab-bot:{token}@{host}", parts.path, "", ""))


def git(where: Path, *args: str) -> subprocess.CompletedProcess[str]:
    """Run git in a directory and hand back the finished process, failures included."""
    return subprocess.run(["git", *args], cwd=where, capture_output=True, text=True, check=False)


def push_wiki(repo: Path, pages: dict[str, str], wiki_url: str, token: str, sha: str) -> int:
    """Clone the wiki, replace the generated pages, commit and push.

    A refused push means another regeneration landed first: fetch, reset onto
    the remote tip and re-apply. A pull would try to merge two generated trees.
    """
    authed = with_token(wiki_url, token)
    workdir = Path(tempfile.mkdtemp(prefix="wiki-"))
    try:
        clone = git(workdir, "clone", "--depth", "1", authed, "wiki")
        if clone.returncode != 0:
            print(clone.stderr.replace(token, "***"), file=sys.stderr)
            print(
                "wiki: clone failed - seed the wiki with one page first (section 3)",
                file=sys.stderr,
            )
            return 1
        checkout = workdir / "wiki"
        for attempt in range(3):
            write_pages(checkout, pages)
            git(checkout, "config", "user.name", "lab-bot")
            git(checkout, "config", "user.email", "lab-bot@additive-lab.local")
            git(checkout, "add", "-A")
            status = git(checkout, "status", "--porcelain")
            if not status.stdout.strip():
                print("wiki: already up to date")
                return 0
            git(checkout, "commit", "-s", "-m", f"docs(docs): regenerate wiki from {sha}")
            pushed = git(checkout, "push", "origin", "HEAD")
            if pushed.returncode == 0:
                print(f"wiki: pushed {len(pages)} pages from {sha[:10]}")
                return 0
            print(f"wiki: push refused, re-applying onto the remote tip (attempt {attempt + 1})")
            git(checkout, "fetch", "origin")
            head = git(checkout, "rev-parse", "--abbrev-ref", "origin/HEAD").stdout.strip()
            git(checkout, "reset", "--hard", head or "origin/master")
        print("wiki: could not push after three attempts", file=sys.stderr)
        return 1
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def packages_from_recipe(repo: Path) -> list[str]:
    """Read $Provides out of recipe.ps1 as text, the way the lab reads it."""
    recipe = (repo / "recipe.ps1").read_text(encoding="utf-8")
    found = re.search(r"(?m)^\s*\$Provides\s*=\s*@\(([^)]*)\)", recipe)
    if not found:
        return []
    return re.findall(r"['\"]([^'\"]+)['\"]", found.group(1))


def main(argv: list[str] | None = None) -> int:
    """Entry point: build the pages, then either write them out or push them."""
    parser = argparse.ArgumentParser(description="Generate the repository wiki.")
    parser.add_argument("--push", action="store_true", help="push to the wiki repository")
    parser.add_argument("--wiki-url", default="", help="the <repo>.wiki.git URL")
    parser.add_argument("--token", default="", help="a token with write:repository")
    parser.add_argument("--sha", default="", help="the commit the pages were generated from")
    parser.add_argument("--out", default="", help="write the pages here instead of pushing")
    args = parser.parse_args(argv)

    repo = Path(__file__).resolve().parent.parent
    sha = args.sha or git(repo, "rev-parse", "HEAD").stdout.strip() or "unknown"
    pages = build_pages(repo, packages_from_recipe(repo) or ["WaamAPI"], sha)

    if args.out:
        where = Path(args.out)
        where.mkdir(parents=True, exist_ok=True)
        write_pages(where, pages)
        print(f"wiki: wrote {len(pages)} pages to {where}")
        return 0
    if not args.push:
        print(f"wiki: {len(pages)} pages would be written: {', '.join(sorted(pages))}")
        return 0
    token = args.token or os.environ.get("LAB_BOT_TOKEN", "") or os.environ.get("TOKEN", "")
    if not args.wiki_url or not token:
        print("wiki: --push needs --wiki-url and --token", file=sys.stderr)
        return 1
    return push_wiki(repo, pages, args.wiki_url, token, sha)


if __name__ == "__main__":
    raise SystemExit(main())
